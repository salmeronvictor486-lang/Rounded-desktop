#!/usr/bin/env node
'use strict';
/** Generates docs/CATALOG.md from the content folders. Run with `npm run catalog`. */
const fs = require('fs');
const path = require('path');
const { load, ROOT } = require('../src/catalog');
const { CORE, LANGUAGE_SKILLS } = require('../src/profiles');

const cell = (s) => String(s || '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const firstSentence = (s) => cell(String(s || '').split(/(?<=\.)\s/)[0]);

function renderCatalog(c) {
  const core = (list, id) => (list.includes(id) ? '✓' : '');
  const langOf = Object.fromEntries(Object.entries(LANGUAGE_SKILLS).flatMap(([l, ids]) => ids.map((id) => [id, l])));
  const out = [
    '# Catalog',
    '',
    '<!-- Generated by `npm run catalog` from the content folders. Do not edit by hand. -->',
    '',
    `Rounded ${c.version} ships ${c.agents.length} agents, ${c.skills.length} skills, ${c.commands.length} commands and ${c.rules.length} rules.`,
    'Items marked **core** are installed by the default `core` profile; `full` installs everything.',
    '',
    '## Agents',
    '',
    'Specialist subagents the main agent can delegate to.',
    '',
    '| Agent | Core | Tools | What it does |',
    '|---|---|---|---|',
    ...c.agents.map((a) => `| [\`${a.id}\`](../agents/${a.id}.md) | ${core(CORE.agents, a.id)} | ${cell(a.tools)} | ${firstSentence(a.description)} |`),
    '',
    '## Skills',
    '',
    'Reusable know-how the agent loads when the task matches the description.',
    '',
    '| Skill | Core | What it covers |',
    '|---|---|---|',
    ...c.skills.map((s) => `| [\`${s.id}\`](../skills/${s.id}/SKILL.md) | ${langOf[s.id] ? `with ${langOf[s.id]}` : core(CORE.skills, s.id)} | ${firstSentence(s.description)} |`),
    '',
    '## Commands',
    '',
    'Slash commands for common workflows.',
    '',
    '| Command | Core | Arguments | What it does |',
    '|---|---|---|---|',
    ...c.commands.map((x) => `| [\`/${x.id}\`](../commands/${x.id}.md) | ${core(CORE.commands, x.id)} | ${cell(x.argumentHint ? `\`${x.argumentHint}\`` : '')} | ${cell(x.description)} |`),
    '',
    '## Rules',
    '',
    'Always-on guidelines. Common rules are always installed; language rules follow the detected or chosen languages.',
    '',
    '| Rule | Applies to | Summary |',
    '|---|---|---|',
    ...c.rules.map((r) => `| [\`${r.group}/${r.id}\`](../rules/${r.group}/${r.id}.md) | ${r.globs ? cell(r.globs.split(',').map((g) => `\`${g}\``).join(' ')) : 'all files'} | ${cell(r.description)} |`),
    '',
  ];
  return out.join('\n');
}

if (require.main === module) {
  const file = path.join(ROOT, 'docs', 'CATALOG.md');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, renderCatalog(load()));
  console.log(`Wrote ${path.relative(ROOT, file)}`);
}

module.exports = { renderCatalog };
