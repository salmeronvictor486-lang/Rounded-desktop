export function resolveFunction(name: string): { canonical: string; def: FnDef } | null {
  const up = name.toUpperCase();
  const canonical = FUNCTIONS[up] ? up : SPANISH_ALIASES[up] ?? null;
  if (!canonical || !FUNCTIONS[canonical]) return null;
  return { canonical, def: FUNCTIONS[canonical] };
}

