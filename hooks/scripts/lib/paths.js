'use strict';
/** Paths the agent should not edit by hand, with the reason. */
const path = require('path');

const LOCKFILES = new Set([
  'package-lock.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lockb', 'bun.lock', 'npm-shrinkwrap.json', 'Cargo.lock',
  'poetry.lock', 'uv.lock', 'Pipfile.lock', 'Gemfile.lock', 'composer.lock', 'go.sum', 'mix.lock', 'pubspec.lock', 'Podfile.lock',
]);

function check(file) {
  if (!file) return null;
  const norm = file.replace(/\\/g, '/');
  const base = path.posix.basename(norm);
  if (/(^|\/)\.git\//.test(norm)) return { level: 'deny', reason: 'Files inside .git/ are managed by git. Use git commands instead of editing them.' };
  if (LOCKFILES.has(base)) return { level: 'ask', reason: `${base} is generated by the package manager. Prefer running the install/update command so it stays consistent.` };
  if (/(^|\/)(node_modules|vendor|\.venv|venv|site-packages)\//.test(norm)) {
    return { level: 'ask', reason: 'This file belongs to an installed dependency; edits are lost on the next install. Patch upstream or use a patch tool.' };
  }
  if (/\.(pem|key|p12|pfx|jks|keystore)$/i.test(base) || /^id_(rsa|ed25519|ecdsa|dsa)$/.test(base)) {
    return { level: 'ask', reason: `${base} looks like a key or certificate. Confirm the agent should write it.` };
  }
  return null;
}

module.exports = { check };
